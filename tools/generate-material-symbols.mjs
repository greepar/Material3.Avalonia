import fs from 'node:fs';
import path from 'node:path';

const input = path.resolve(process.argv[2] ?? '');
const output = path.resolve(process.argv[3] ?? 'src/Material3.Avalonia/Icons/Generated');

if (!input || !fs.existsSync(input)) {
  throw new Error('Usage: node tools/generate-material-symbols.mjs <iconify-icons.json> [output-directory]');
}

const iconSet = JSON.parse(fs.readFileSync(input, 'utf8'));
const names = new Set([...Object.keys(iconSet.icons), ...Object.keys(iconSet.aliases ?? {})]);
const resolveBody = name => {
  const visited = new Set();
  let current = name;
  while (iconSet.aliases?.[current]) {
    if (visited.has(current)) {
      throw new Error(`Circular icon alias: ${name}`);
    }
    visited.add(current);
    current = iconSet.aliases[current].parent;
  }

  const body = iconSet.icons[current]?.body;
  if (!body) {
    throw new Error(`No icon body found for ${name}`);
  }

  const paths = [...body.matchAll(/\bd="([^"]+)"/g)].map(match => match[1]);
  if (paths.length === 0) {
    throw new Error(`No path data found for ${name}`);
  }
  return paths.join(' ');
};

const entries = [...names]
  .filter(name => name.endsWith('-rounded') && !name.endsWith('-outline-rounded'))
  .map(filledName => {
    const name = filledName.slice(0, -'-rounded'.length);
    const regularName = `${name}-outline-rounded`;
    return names.has(regularName)
      ? { name, regular: resolveBody(regularName), filled: resolveBody(filledName) }
      : null;
  })
  .filter(Boolean)
  .sort((left, right) => left.name.localeCompare(right.name));

const packageJsonPath = path.join(path.dirname(input), 'package.json');
const packageInfo = fs.existsSync(packageJsonPath)
  ? JSON.parse(fs.readFileSync(packageJsonPath, 'utf8'))
  : { name: '@iconify-json/material-symbols', version: 'unknown' };

const identifiers = new Map();
const toIdentifier = name => {
  const identifier = name.split(/[^a-zA-Z0-9]+/)
    .filter(Boolean)
    .map(part => part[0].toUpperCase() + part.slice(1))
    .join('');
  const result = /^[0-9]/.test(identifier) ? `Icon${identifier}` : identifier;
  if (!result || !/^[A-Za-z_][A-Za-z0-9_]*$/.test(result)) {
    throw new Error(`Cannot create C# identifier for ${name}`);
  }
  const previous = identifiers.get(result);
  if (previous && previous !== name) {
    throw new Error(`Identifier collision: ${previous} and ${name} -> ${result}`);
  }
  identifiers.set(result, name);
  return result;
};

const escape = value => value.replaceAll('\\', '\\\\').replaceAll('"', '\\"');
const buckets = new Map();
for (const entry of entries) {
  const identifier = toIdentifier(entry.name);
  entry.identifier = identifier;
  const bucket = identifier[0].toUpperCase();
  const list = buckets.get(bucket) ?? [];
  list.push({ ...entry, identifier });
  buckets.set(bucket, list);
}

fs.mkdirSync(output, { recursive: true });
for (const existing of fs.readdirSync(output)) {
  if (existing.endsWith('.g.cs')) {
    fs.rmSync(path.join(output, existing));
  }
}

const header = `// <auto-generated />\n// Generated from Google Material Symbols Rounded 400, optical size 24.\n// Do not edit this file manually.\n\n#nullable enable\n\nusing Avalonia.Media;\n\nnamespace Material3.Avalonia.Icons;\n\n`;
const render = (className, property) => {
  const lines = [header, `public static partial class ${className}`, '{'];
  for (const entry of property) {
    lines.push(`    private static Geometry? s_${entry.identifier};`);
    lines.push(`    public static Geometry ${entry.identifier} => MaterialSymbolGeometry.Get(ref s_${entry.identifier}, "${escape(entry.path)}");`);
    lines.push('');
  }
  lines.push('}');
  return lines.join('\n');
};

for (const [bucket, bucketEntries] of buckets) {
  fs.writeFileSync(path.join(output, `MaterialSymbols${bucket}.g.cs`), render('MaterialSymbols', bucketEntries.map(entry => ({ ...entry, path: entry.regular }))));
  fs.writeFileSync(path.join(output, `MaterialSymbolsFilled${bucket}.g.cs`), render('MaterialSymbolsFilled', bucketEntries.map(entry => ({ ...entry, path: entry.filled }))));
}

const catalogLines = [
  header,
  'public static class MaterialSymbolCatalog',
  '{',
  '    private static readonly MaterialSymbolInfo[] s_all =',
  '    [',
];
for (const [index, entry] of entries.entries()) {
  catalogLines.push(`        new(${index}, "${escape(entry.name)}", "${entry.identifier}"),`);
}
catalogLines.push(
  '    ];',
  '',
  '    private static readonly IReadOnlyList<MaterialSymbolInfo> s_allView = Array.AsReadOnly(s_all);',
  '',
  '    public static IReadOnlyList<MaterialSymbolInfo> All => s_allView;',
  '',
  '    public static Geometry GetGeometry(int index, bool filled = false) => filled',
  '        ? GetFilledGeometry(index)',
  '        : GetRegularGeometry(index);',
  '',
  '    private static Geometry GetRegularGeometry(int index) => index switch',
  '    {',
);
for (const [index, entry] of entries.entries()) {
  catalogLines.push(`        ${index} => MaterialSymbols.${entry.identifier},`);
}
catalogLines.push(
  '        _ => throw new ArgumentOutOfRangeException(nameof(index)),',
  '    };',
  '',
  '    private static Geometry GetFilledGeometry(int index) => index switch',
  '    {',
);
for (const [index, entry] of entries.entries()) {
  catalogLines.push(`        ${index} => MaterialSymbolsFilled.${entry.identifier},`);
}
catalogLines.push(
  '        _ => throw new ArgumentOutOfRangeException(nameof(index)),',
  '    };',
  '}',
);
fs.writeFileSync(path.join(output, 'MaterialSymbolCatalog.g.cs'), catalogLines.join('\n'));

const manifest = {
  source: `${packageInfo.name}@${packageInfo.version}`,
  family: 'rounded',
  weight: 400,
  opticalSize: 24,
  count: entries.length,
  variants: ['regular', 'filled'],
};
fs.writeFileSync(path.join(output, 'material-symbols-manifest.json'), `${JSON.stringify(manifest, null, 2)}\n`);
console.log(`Generated ${entries.length} icons and ${entries.length * 2} variants in ${output}`);
